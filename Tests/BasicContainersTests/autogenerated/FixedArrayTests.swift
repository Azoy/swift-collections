@available(SwiftStdlib 6.2, *)
internal func expectFixedArrayContents<
  let capacity: Int,
  Element: Equatable,
  C2: Collection<Element>,
>(
  _ left: borrowing FixedArray<capacity, Element>,
  equalTo right: C2,
  _ message: @autoclosure () -> String = "",
  trapping: Bool = false,
  file: StaticString = #filePath,
  line: UInt = #line
) {
  expectIterableContents(
    left.span,
    equalTo: right,
    message(), trapping: trapping, file: file, line: line)
}

/// Check if `left` and `right` contain equal elements in the same order.
@available(SwiftStdlib 6.2, *)
internal func expectFixedArrayContents<
  let capacity: Int,
  E1: ~Copyable,
  C2: Collection,
>(
  _ left: borrowing FixedArray<capacity, E1>,
  equivalentTo right: C2,
  by areEquivalent: (borrowing E1, C2.Element) -> Bool,
  printer: (borrowing E1) -> String,
  _ message: @autoclosure () -> String = "",
  trapping: Bool = false,
  file: StaticString = #filePath,
  line: UInt = #line
) {
  expectIterableContents(
    left.span,
    equivalentTo: right,
    by: areEquivalent,
    printer: printer,
    message(), trapping: trapping, file: file, line: line)
}

