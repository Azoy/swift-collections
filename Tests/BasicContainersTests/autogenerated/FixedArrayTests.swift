internal func expectFixedArrayContents<
  let capacity: Int,
  Element: Equatable,
  C2: Collection<Element>,
>(
  _ left: borrowing FixedArray<capacity, Element>,
  equalTo right: C2,
  _ message: @autoclosure () -> String = "",
